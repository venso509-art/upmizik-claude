--  - daily_quotes: sitasyon yo (admin ajoute / modifye / efase / dezaktive)
--  - quote_day_topics: sijè chak jou nan semèn nan (null = melanje)
--  - artist_daily_cards: ki sitasyon + ki desen (1–6) chak atis resevwa chak jou
--  - my_daily_card(): kat jou a pou atis ki konekte a (menm kat la tout jounen an)
--      * Jou a chanje a minwi lè Ayiti (America/Port-au-Prince)
--      * Sitasyon: nan sijè jou a; sa atis la poko janm wè yo an premye, answit sa l wè
--        depi pi lontan (konsa pa gen repetisyon anvan tout fin pase)
--      * Si jou a pa gen sijè: yon lòt kategori pase sa yè a
--      * Desen: pa janm menm jan ak yè, epi sa l itilize mwens nan 12 dènye jou yo
--      * "Aza" a fiks pou (atis, jou): 2 atis diferan jwenn 2 kat diferan
--  Sitasyon yo menm antre ak fichye 20270101000001_daily_quotes_seed.sql
