create table if not exists public.daily_quotes (
  id         integer generated by default as identity primary key,
  kategori   text not null check (kategori ~ '^[a-z_]{2,30}$'),
  etiket     text not null check (char_length(trim(etiket)) between 2 and 40),
  teks       text not null check (char_length(trim(teks)) between 2 and 140),
  sous       text check (char_length(sous) <= 80),
  active     boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists daily_quotes_kategori_idx on public.daily_quotes (kategori) where active;

create table if not exists public.quote_day_topics (
  weekday  smallint primary key check (weekday between 0 and 6), -- 0 = Dimanch … 6 = Samdi
  kategori text check (kategori ~ '^[a-z_]{2,30}$')               -- null = melanje
);
-- Sijè pa defo (admin nan ka chanje yo nan Admin → Sitasyon)
insert into public.quote_day_topics (weekday, kategori) values
  (1, 'motivasyon'), (2, 'mizik'), (3, 'blag'), (4, 'lanmou'), (5, 'atis_travay'), (6, 'ede_pwochen'), (0, null)
on conflict (weekday) do nothing;

create table if not exists public.artist_daily_cards (
  artist_id  uuid not null references public.profiles (id) on delete cascade,
  day        date not null,
  quote_id   integer not null references public.daily_quotes (id) on delete cascade,
  template   smallint not null check (template between 1 and 6),
  created_at timestamptz not null default now(),
  primary key (artist_id, day)
);
create index if not exists artist_daily_cards_quote_idx on public.artist_daily_cards (artist_id, quote_id);

alter table public.daily_quotes enable row level security;
alter table public.quote_day_topics enable row level security;
alter table public.artist_daily_cards enable row level security;

drop policy if exists "Admin jere sitasyon yo" on public.daily_quotes;
create policy "Admin jere sitasyon yo" on public.daily_quotes for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "Moun konekte wè sijè yo" on public.quote_day_topics;
create policy "Moun konekte wè sijè yo" on public.quote_day_topics for select to authenticated using (true);
drop policy if exists "Admin chanje sijè yo" on public.quote_day_topics;
create policy "Admin chanje sijè yo" on public.quote_day_topics for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

-- Atis la wè sèlman pwòp kat li yo; se my_daily_card() sèlman ki kreye yo
drop policy if exists "Atis la wè kat li yo" on public.artist_daily_cards;
create policy "Atis la wè kat li yo" on public.artist_daily_cards for select to authenticated
  using (artist_id = (select auth.uid()) or (select public.is_admin()));

create or replace function public.my_daily_card()
returns table (day date, template smallint, quote_id integer, teks text, kategori text, etiket text, sous text)
language plpgsql
security definer set search_path = ''
as $$
declare
  v_uid       uuid := auth.uid();
  v_day       date := (now() at time zone 'America/Port-au-Prince')::date;
  v_card      public.artist_daily_cards;
  v_yest      public.artist_daily_cards;
  v_yest_kat  text;
  v_topic     text;
  v_quote     integer;
  v_tpl       smallint;
begin
  if v_uid is null or not exists (select 1 from public.profiles p where p.id = v_uid and p.role = 'artist') then
    return;
  end if;

  select * into v_card from public.artist_daily_cards c where c.artist_id = v_uid and c.day = v_day;
  if v_card.artist_id is null then
    select * into v_yest from public.artist_daily_cards c where c.artist_id = v_uid and c.day = v_day - 1;
    select q.kategori into v_yest_kat from public.daily_quotes q where q.id = v_yest.quote_id;
    select t.kategori into v_topic from public.quote_day_topics t where t.weekday = extract(dow from v_day)::smallint;

    -- Sitasyon: sijè jou a (oswa yon lòt kategori pase yè), sa l poko wè an premye
    with last_seen as (
      select c.quote_id as qid, max(c.day) as d from public.artist_daily_cards c where c.artist_id = v_uid group by c.quote_id
    )
    select q.id into v_quote
    from public.daily_quotes q
    left join last_seen ls on ls.qid = q.id
    where q.active
      and (v_topic is null or q.kategori = v_topic)
      and (v_topic is not null or v_yest_kat is null or q.kategori <> v_yest_kat)
    order by ls.d nulls first, md5(v_uid::text || v_day::text || q.id::text)
    limit 1;

    -- Pa gen sitasyon nan sijè sa a: nenpòt sitasyon aktif
    if v_quote is null then
      with last_seen as (
        select c.quote_id as qid, max(c.day) as d from public.artist_daily_cards c where c.artist_id = v_uid group by c.quote_id
      )
      select q.id into v_quote
      from public.daily_quotes q
      left join last_seen ls on ls.qid = q.id
      where q.active
      order by ls.d nulls first, md5(v_uid::text || v_day::text || q.id::text)
      limit 1;
    end if;
    if v_quote is null then
      return; -- poko gen sitasyon: "Pawòl jou a ap vini byento"
    end if;

    -- Desen: pa menm jan ak yè, epi sa l itilize mwens nan 12 dènye jou yo
    select t::smallint into v_tpl
    from generate_series(1, 6) t
    where v_yest.template is null or t <> v_yest.template
    order by (select count(*) from public.artist_daily_cards c
              where c.artist_id = v_uid and c.day > v_day - 12 and c.template = t),
             md5(v_uid::text || v_day::text || t::text)
    limit 1;

    insert into public.artist_daily_cards (artist_id, day, quote_id, template)
    values (v_uid, v_day, v_quote, v_tpl)
    on conflict on constraint artist_daily_cards_pkey do nothing;

    select * into v_card from public.artist_daily_cards c where c.artist_id = v_uid and c.day = v_day;
  end if;

  return query
  select v_card.day, v_card.template, q.id, q.teks, q.kategori, q.etiket, q.sous
  from public.daily_quotes q
  where q.id = v_card.quote_id;
end;
$$;

revoke execute on function public.my_daily_card() from public, anon;
grant execute on function public.my_daily_card() to authenticated;
